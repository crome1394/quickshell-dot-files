#!/usr/bin/env bash
# opacity-apply.sh — persist and apply Quickshell transparency sliders.
# Usage:
#   opacity-apply.sh get
#   opacity-apply.sh set <apps 0|5-100> <satty 0|5-100>
# 0 means that slider has never been set, so existing window rules stay.
set -euo pipefail

STATE="${OPACITY_STATE:-$HOME/.config/hypr/opacity.state}"
LUA="${OPACITY_LUA:-$HOME/.config/hypr/opacity.lua}"
LOCK="${OPACITY_LOCK:-$HOME/.config/hypr/opacity.lock}"

usage() {
    echo "usage: opacity-apply.sh get | set <apps> <satty>" >&2
    exit 2
}

valid_pct() {
    local n="$1"
    [[ "$n" =~ ^[0-9]+$ ]] || return 1
    [[ "$n" -eq 0 || ( "$n" -ge 5 && "$n" -le 100 ) ]]
}

read_state() {
    apps=0
    satty=0
    if [[ -f "$STATE" ]]; then
        local line key val
        while IFS= read -r line || [[ -n "$line" ]]; do
            key="${line%%=*}"
            val="${line#*=}"
            case "$key" in
                apps) valid_pct "$val" && apps="$val" ;;
                satty) valid_pct "$val" && satty="$val" ;;
            esac
        done < "$STATE"
    fi
}

write_state() {
    local tmp
    tmp="$(mktemp "${STATE}.XXXXXX")"
    printf 'apps=%s\nsatty=%s\n' "$apps" "$satty" > "$tmp"
    mv -f "$tmp" "$STATE"
}

write_lua() {
    local satty_pct="$satty"
    if [[ "$satty" -eq 0 ]]; then
        satty_pct=100
    fi
    local tmp
    tmp="$(mktemp "${LUA}.XXXXXX")"
    {
        echo '-- Generated by opacity-apply.sh. Loaded after the other window rules.'
        echo '-- apps/satty 0 means that slider is unset and this file adds no rule for it.'
        echo '_G.QS_OPACITY = _G.QS_OPACITY or {}'
        echo 'local function add(spec)'
        echo '    local rule = hl.window_rule(spec)'
        echo '    _G.QS_OPACITY[#_G.QS_OPACITY + 1] = rule'
        echo 'end'
        echo 'local function levels(pct)'
        echo '    local s = string.format("%.2f", pct / 100)'
        echo '    return s .. " override " .. s .. " override"'
        echo 'end'
        if [[ "$apps" -ge 5 ]]; then
            echo "add({ name = \"qs-opacity-apps\", match = { class = \".*\" }, opacity = levels(${apps}) })"
            echo 'add({ name = "qs-opacity-settings", match = { class = "^org\\.quickshell$", title = "^Settings$" }, opacity = "1 override 1 override 1 override" })'
            echo 'add({ name = "qs-opacity-fullscreen", match = { fullscreen = true }, opacity = "1 override 1 override 1 override" })'
        fi
        if [[ "$satty" -ge 5 || "$apps" -ge 5 ]]; then
            # Lua source needs \\ so the regex string contains \.
            echo "add({ name = \"qs-opacity-satty\", match = { class = \"^com\\\\.gabm\\\\.satty$\" }, opacity = levels(${satty_pct}) })"
        fi
    } > "$tmp"
    mv -f "$tmp" "$LUA"
}

apply_live() {
    local live out
    live="$(mktemp)"
    cat > "$live" << EOF
if _G.QS_OPACITY then
    for i = 1, #_G.QS_OPACITY do
        local rule = _G.QS_OPACITY[i]
        if rule then rule:set_enabled(false) end
    end
end
_G.QS_OPACITY = {}
dofile("${LUA}")
return "ok"
EOF
    if [[ -z "${HYPRLAND_INSTANCE_SIGNATURE:-}" ]]; then
        rm -f "$live"
        return 0
    fi
    out="$(hyprctl repl "$(cat "$live")" 2>&1 || true)"
    rm -f "$live"
    case "$out" in
        error:*|'' )
            echo "error: hyprctl repl failed: ${out:-no output}" >&2
            return 1
            ;;
    esac
}

cmd="${1:-}"
case "$cmd" in
    get)
        read_state
        printf 'apps=%s\nsatty=%s\n' "$apps" "$satty"
        ;;
    set)
        [[ $# -eq 3 ]] || usage
        valid_pct "$2" && valid_pct "$3" || usage
        exec 9>"$LOCK"
        flock -w 3 9
        apps="$2"
        satty="$3"
        write_state
        write_lua
        apply_live
        ;;
    *)
        usage
        ;;
esac
